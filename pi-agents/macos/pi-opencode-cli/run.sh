#!/usr/bin/env bash
#
# run.sh — pi-opencode-cli: run the pi coding agent in your terminal on OpenCode's FREE models.
#
#   pi (its own tools, your cwd) ──▶ pure-LLM OpenCode bridge :18386 ──▶ `opencode run` (all tools denied)
#                                    tool calls emulated over text by the shared pi provider
#
# Usage (from this folder):
#   ./run.sh upstream          # foreground pure-LLM OpenCode bridge on :18386 (leave running)
#   ./run.sh pi [args…]        # start pi with this provider, in the CURRENT directory
#   ./run.sh test              # headless pi run: the model must call pi's bash tool itself
#   ./run.sh models            # models the bridge advertises (opencode free tier)
#   ./run.sh install-service   # bridge as an auto-start user service (launchd / systemd --user)
#   ./run.sh uninstall-service | service-status | logs
#
# Config (env or .env next to this script): UPSTREAM_PORT 18386, PI_CLI_MODEL opencode/mimo-v2.5-free,
#   PI_CLI_GUARDRAILS (1 = load the shared approvals extension), OPENCODE_BIN, OPENCODE_BRIDGE_TIMEOUT
set -euo pipefail

HERE="$(cd -P "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
[ -f "$HERE/.env" ] && { set -a; . "$HERE/.env"; set +a; }
COMMON="$HERE/../common"
OPENCODE_LAUNCHER="$HERE/../../../opencode/hermes-desktop/run-bridge.sh"
PURE_LLM_CONFIG="$HERE/../opencode/opencode/pure-llm.json"
UPSTREAM_PORT="${UPSTREAM_PORT:-18386}"
MODEL="${PI_CLI_MODEL:-opencode/mimo-v2.5-free}"
LABEL="com.hermes.opencode-pi-cli"
LOG_FILE="${PI_CLI_LOG:-$HOME/.pi-cli-opencode.log}"
SERVICE_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/pi-cli-opencode"
PI_BIN="${PI_BIN:-$(command -v pi || echo "$HOME/.local/bin/pi")}"

shell_quote() { local q; printf -v q '%q' "$1"; printf '%s' "$q"; }
xml_escape() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
os_kind() { case "$(uname -s)" in Darwin) echo mac;; Linux) echo linux;; *) echo other;; esac; }
require() {
  command -v opencode >/dev/null 2>&1 || [ -n "${OPENCODE_BIN:-}" ] || { echo "[pi-opencode-cli] error: opencode not on PATH (https://opencode.ai)" >&2; exit 1; }
  [ -x "$OPENCODE_LAUNCHER" ] || { echo "[pi-opencode-cli] error: $OPENCODE_LAUNCHER missing" >&2; exit 1; }
  [ -f "$PURE_LLM_CONFIG" ]   || { echo "[pi-opencode-cli] error: $PURE_LLM_CONFIG missing" >&2; exit 1; }
}

cmd_upstream() {
  require
  echo "[pi-opencode-cli] pure-LLM OpenCode bridge on :${UPSTREAM_PORT} — OpenCode's own tools are all denied; pi runs the tools"
  # Own port + own launchd label so this instance never collides with the Hermes stack (:18385).
  BRIDGE_PORT="$UPSTREAM_PORT" OPENCODE_CONFIG="$PURE_LLM_CONFIG" OPENCODE_BRIDGE_LABEL="$LABEL" \
  OPENCODE_BRIDGE_MODEL="$MODEL" OPENCODE_BRIDGE_CWD="${OPENCODE_BRIDGE_CWD:-$HOME}" \
  OPENCODE_BRIDGE_TIMEOUT="${OPENCODE_BRIDGE_TIMEOUT:-600}" \
  OPENCODE_BRIDGE_MAX_CONCURRENCY="${OPENCODE_BRIDGE_MAX_CONCURRENCY:-2}" \
    exec "$OPENCODE_LAUNCHER" run
}

# After install.sh the extension is already in ~/.pi/agent/settings.json — don't load it twice.
# PI_CLI_GUARDRAILS=1 adds the shared Codex-style approvals extension (off by default, like pi-cli).
ext_args() {
  grep -qsF "$HERE/extensions/opencode-cli" "$HOME/.pi/agent/settings.json" 2>/dev/null || printf -- '-e\n%s\n' "$HERE/extensions/opencode-cli"
  case "${PI_CLI_GUARDRAILS:-0}" in 1|true|yes|on) printf -- '-e\n%s\n' "$COMMON/extensions/guardrails" ;; esac
}

cmd_pi() {
  [ -x "$PI_BIN" ] || { echo "[pi-opencode-cli] error: pi not found — npm install -g @earendil-works/pi-coding-agent" >&2; exit 1; }
  curl -fsS "http://127.0.0.1:${UPSTREAM_PORT}/health" >/dev/null 2>&1 || \
    echo "[pi-opencode-cli] note: bridge :${UPSTREAM_PORT} not answering — run: $0 upstream   (or $0 install-service)"
  local -a ext=(); while IFS= read -r line; do ext+=("$line"); done < <(ext_args)
  exec "$PI_BIN" ${ext[@]+"${ext[@]}"} --provider opencode-cli --model "$MODEL" "$@"
}

cmd_test() {
  local dir; dir="$(mktemp -d "${TMPDIR:-/tmp}/pi-opencode-cli-test.XXXX")"
  local -a ext=(); while IFS= read -r line; do ext+=("$line"); done < <(ext_args)
  echo "[pi-opencode-cli] headless pi in $dir — expect the free model to CALL pi's bash tool, not describe it:"
  ( cd "$dir" && printf '%s' "Use your bash tool to run: pwd && echo pi-opencode-cli-ok. Then report the output." \
    | PI_APPROVAL_NONINTERACTIVE="${PI_APPROVAL_NONINTERACTIVE:-allow}" \
      "$PI_BIN" -p --no-session ${ext[@]+"${ext[@]}"} --provider opencode-cli --model "$MODEL" )
  echo; rmdir "$dir" 2>/dev/null || true
}

cmd_models() { curl -fsS "http://127.0.0.1:${UPSTREAM_PORT}/v1/models" | python3 -c 'import sys,json; [print(m["id"]) for m in json.load(sys.stdin)["data"]]'; }

write_runner() {
  mkdir -p "$SERVICE_DIR"
  {
    printf '#!/usr/bin/env bash\n# Auto-generated by %s install-service.\nset -euo pipefail\n' "$0"
    printf 'export PATH=/opt/homebrew/bin:/usr/local/bin:%s/.local/bin:%s/.opencode/bin:/usr/bin:/bin:"$PATH"\n' "$(shell_quote "$HOME")" "$(shell_quote "$HOME")"
    for v in UPSTREAM_PORT PI_CLI_MODEL OPENCODE_BIN OPENCODE_BRIDGE_CWD OPENCODE_BRIDGE_TIMEOUT OPENCODE_BRIDGE_MAX_CONCURRENCY; do
      [ -n "${!v:-}" ] && printf 'export %s=%s\n' "$v" "$(shell_quote "${!v}")"
    done
    printf 'exec %s upstream\n' "$(shell_quote "$HERE/run.sh")"
  } > "$SERVICE_DIR/run-upstream.sh"
  chmod 755 "$SERVICE_DIR/run-upstream.sh"
}
cmd_install_service() {
  require; write_runner
  # a leftover foreground bridge on the port would make the service crash-loop
  local pid; pid="$(lsof -tnP -iTCP:"$UPSTREAM_PORT" -sTCP:LISTEN 2>/dev/null | head -1 || true)"
  if [ -n "$pid" ] && ! ps -o command= -p "$pid" | grep -q "pi-cli-opencode/run-upstream"; then
    echo "[pi-opencode-cli] port $UPSTREAM_PORT held by pid $pid — stopping it"; kill "$pid" 2>/dev/null || true; sleep 1; fi
  case "$(os_kind)" in
    mac)
      local plist="$HOME/Library/LaunchAgents/$LABEL.plist" domain="gui/$(id -u)" i
      mkdir -p "$(dirname "$plist")"
      {
        printf '<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0"><dict>\n'
        printf '  <key>Label</key><string>%s</string>\n  <key>ProgramArguments</key><array><string>%s</string></array>\n' "$LABEL" "$(xml_escape "$SERVICE_DIR/run-upstream.sh")"
        printf '  <key>RunAtLoad</key><true/>\n  <key>KeepAlive</key><true/>\n'
        printf '  <key>StandardOutPath</key><string>%s</string>\n  <key>StandardErrorPath</key><string>%s</string>\n</dict></plist>\n' "$(xml_escape "$LOG_FILE")" "$(xml_escape "$LOG_FILE")"
      } > "$plist"
      launchctl bootout "$domain/$LABEL" >/dev/null 2>&1 || true
      for i in $(seq 1 40); do launchctl print "$domain/$LABEL" >/dev/null 2>&1 || break; sleep 0.25; done
      launchctl bootstrap "$domain" "$plist" >/dev/null 2>&1 || launchctl load -w "$plist"
      launchctl enable "$domain/$LABEL" >/dev/null 2>&1 || true
      echo "[pi-opencode-cli] launchd: $LABEL → $plist (log $LOG_FILE)" ;;
    linux)
      local unit="$HOME/.config/systemd/user/$LABEL.service"; mkdir -p "$(dirname "$unit")"
      printf '[Unit]\nDescription=pi-opencode-cli: pure-LLM OpenCode bridge for pi\nAfter=network-online.target\n\n[Service]\nType=simple\nExecStart=%s\nRestart=always\nRestartSec=3\nStandardOutput=append:%s\nStandardError=append:%s\n\n[Install]\nWantedBy=default.target\n' "$SERVICE_DIR/run-upstream.sh" "$LOG_FILE" "$LOG_FILE" > "$unit"
      systemctl --user daemon-reload; systemctl --user enable --now "$LABEL.service"; loginctl enable-linger "$USER" >/dev/null 2>&1 || true
      echo "[pi-opencode-cli] systemd: $LABEL → $unit" ;;
    *) echo "[pi-opencode-cli] unsupported OS for a service; use: $0 upstream" >&2; exit 1 ;;
  esac
  # First boot also discovers the free-model catalogue from `opencode models` — that can take a while.
  printf '[pi-opencode-cli] waiting for http://127.0.0.1:%s/health ' "$UPSTREAM_PORT"
  local i; for i in $(seq 1 240); do curl -fsS "http://127.0.0.1:${UPSTREAM_PORT}/health" >/dev/null 2>&1 && { echo; return 0; }; printf '.'; sleep 0.5; done
  echo; echo "[pi-opencode-cli] warning: bridge not healthy yet — check: $0 logs" >&2; return 1
}
cmd_uninstall_service() {
  case "$(os_kind)" in
    mac)   launchctl bootout "gui/$(id -u)/$LABEL" >/dev/null 2>&1 || true; rm -f "$HOME/Library/LaunchAgents/$LABEL.plist" ;;
    linux) systemctl --user disable --now "$LABEL.service" >/dev/null 2>&1 || true; rm -f "$HOME/.config/systemd/user/$LABEL.service"; systemctl --user daemon-reload ;;
  esac
  rm -f "$SERVICE_DIR/run-upstream.sh"; echo "[pi-opencode-cli] service removed"
}
cmd_status() { case "$(os_kind)" in mac) launchctl list 2>/dev/null | grep -F "$LABEL" || echo "[pi-opencode-cli] not loaded";; linux) systemctl --user status "$LABEL.service" --no-pager 2>/dev/null || echo "[pi-opencode-cli] not installed";; esac; }

case "${1:-pi}" in
  upstream)          cmd_upstream ;;
  pi)                shift; cmd_pi "$@" ;;
  test)              cmd_test ;;
  models)            cmd_models ;;
  install-service)   cmd_install_service ;;
  uninstall-service) cmd_uninstall_service ;;
  service-status)    cmd_status ;;
  logs)              touch "$LOG_FILE"; tail -f "$LOG_FILE" ;;
  help|-h|--help)    awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0" ;;
  *) echo "[pi-opencode-cli] unknown command: $1 (try: $0 help)" >&2; exit 1 ;;
esac
